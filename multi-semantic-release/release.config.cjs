// Default semantic-release configuration of the multi-semantic-release action, applied to every package of the
// monorepo (used when the repository has no semantic-release config of its own). Branch main, Conventional
// Commits filtered by the package's directory (multi-semantic-release), one CHANGELOG.md per package committed by
// the release bot, one GitHub release per package tag (<package>@<version>, tag format of multi-semantic-release)
// without PR/issue comments and labels. Changelog title via the action input (environment variable below).
const changelogTitle =
  process.env.SHARED_RELEASE_CHANGELOG_TITLE ||
  '# Changelog\n\nAll notable changes to this module are documented in this file. It is generated by ' +
    '[semantic-release](https://github.com/semantic-release/semantic-release) from ' +
    '[Conventional Commits](https://www.conventionalcommits.org/). The module adheres to ' +
    '[Semantic Versioning](https://semver.org/spec/v2.0.0.html).';

module.exports = {
  branches: ['main'],
  plugins: [
    [
      '@semantic-release/commit-analyzer',
      {
        preset: 'conventionalcommits',
        // build(deps): dependency updates that change the shipped artifact → patch release
        releaseRules: [{ type: 'build', scope: 'deps', release: 'patch' }],
      },
    ],
    [
      '@semantic-release/release-notes-generator',
      {
        preset: 'conventionalcommits',
        presetConfig: {
          types: [
            { type: 'feat', section: 'Features' },
            { type: 'fix', section: 'Bug Fixes' },
            { type: 'perf', section: 'Performance Improvements' },
            { type: 'revert', section: 'Reverts' },
            { type: 'build', scope: 'deps', section: 'Dependencies' },
            { type: 'build', hidden: true },
            { type: 'chore', hidden: true },
            { type: 'ci', hidden: true },
            { type: 'docs', hidden: true },
            { type: 'refactor', hidden: true },
            { type: 'style', hidden: true },
            { type: 'test', hidden: true },
          ],
        },
      },
    ],
    // paths are relative to the package directory (multi-semantic-release runs each package in its directory)
    ['@semantic-release/changelog', { changelogFile: 'CHANGELOG.md', changelogTitle }],
    [
      '@semantic-release/git',
      {
        assets: ['CHANGELOG.md'],
        message: 'chore(release): ${nextRelease.gitTag} [skip ci]\n\n${nextRelease.notes}',
      },
    ],
    ['@semantic-release/github', { successComment: false, failComment: false, releasedLabels: false }],
  ],
};
